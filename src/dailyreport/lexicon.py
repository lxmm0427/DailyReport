@lru_cache(maxsize=None)
def _platform_regex() -> re.Pattern:
    keys = sorted(platform_aliases(), key=len, reverse=True)
    return re.compile("|".join(re.escape(k) for k in keys))


def resolve_platform(cands: list[str], country: str | None, kind_hint: str | None = None) -> str:
    """同一别名对应多个标准平台时，用国家和类别消歧。"""
    if len(cands) == 1:
        return cands[0]
    pool = cands
    if kind_hint:
        pool = [c for c in pool if PLATFORM_KIND[c] == kind_hint] or pool
    if country:
        owned = [c for c in pool if country in VALID_OWNERS.get(c, {country})]
        pool = owned or pool
    return sorted(pool, key=len)[0]


def find_platforms(text: str) -> list[tuple[int, int, list[str]]]:
    """返回 (start, end, 候选标准名) 列表，按位置排序，最长匹配。"""
    t = _norm(text)
    return [(m.start(), m.end(), platform_aliases()[m.group(0)]) for m in _platform_regex().finditer(t)]


@lru_cache(maxsize=None)
def _region_regex() -> re.Pattern:
    keys = set(REGION_TO_DIRECTION) | set(REGION_ALIASES)
    alt = "|".join(re.escape(k) for k in sorted(keys, key=len, reverse=True))
    # “日本海上自卫队”“菲律宾海军”等不是海域
    return re.compile(f"(?:{alt})(?!军|上自卫|上保安|警)")


def canonical_region(s: str) -> str:
    return REGION_ALIASES.get(s, s)


def find_regions(text: str) -> list[tuple[int, str]]:
    return [(m.start(), canonical_region(m.group(0))) for m in _region_regex().finditer(text)]


def region_direction(region: str | None) -> str:
    if not region:
        return "其他"
    return REGION_TO_DIRECTION.get(canonical_region(region), "其他")


def nearest_region(lon: float, lat: float) -> tuple[str, float]:
    best, bd = "其他", 1e9
    for r, (x, y) in REGION_ANCHORS.items():
        d = ((x - lon) ** 2 + (y - lat) ** 2) ** 0.5
        if d < bd:
            best, bd = r, d
    return best, bd


def anchor_distance(region: str, lon: float, lat: float) -> float | None:
    a = REGION_ANCHORS.get(canonical_region(region))
    if not a:
        return None
    return ((a[0] - lon) ** 2 + (a[1] - lat) ** 2) ** 0.5
